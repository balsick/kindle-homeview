#!/usr/bin/env python3
"""Generates the QR codes the Kindle shows with the Home key.

    python3 tools/make_qr.py

Asks for the guest WiFi network and password and creates in kindle/qr/:
  wifi.png  QR code to join the WiFi
  app.png   QR code to open the Arduino's webapp (http://ARDUINO_HOST/)
  *.raw     the same QR codes, ready for the Kindle's framebuffer
  info.sh   text shown under the QR codes

kindle/qr/ holds the password in clear text: it's kept out of the repository
and only goes onto the Kindle (in /mnt/us/dashboard/qr/).

Needs segno (pip install segno).
"""

import argparse
import getpass
import re
from pathlib import Path

import segno
import segno.helpers

ROOT = Path(__file__).resolve().parent.parent
WIFI_PX = 300  # max QR side in pixels on the 600x800 screen
APP_PX = 200
SCREEN_W = 600


def save_qr(qr, path, max_px):
    # Whole modules and the standard border of 4: sharp, readable QR on e-ink
    modules = qr.symbol_size(scale=1, border=4)[0]
    scale = max(1, max_px // modules)
    qr.save(str(path), kind="png", scale=scale, border=4)
    save_raw(qr, path.with_suffix(".raw"), scale)


def save_raw(qr, path, scale):
    """The QR code as a screen-wide strip, one byte per pixel (255 black,
    0 white), centered: dashboard.sh copies it with dd into the Kindle's
    framebuffer, because KOReader's FBInk can't draw images."""
    rows = []
    for row in qr.matrix_iter(scale=scale, border=4):
        line = bytes(255 if dark else 0 for dark in row)
        left = (SCREEN_W - len(line)) // 2
        rows.append(bytes(left) + line + bytes(SCREEN_W - left - len(line)))
    path.write_bytes(b"".join(rows))


def shell_quote(s):
    return "'" + s.replace("'", "'\\''") + "'"


def arduino_host_from_config():
    for name in ("config.sh", "defaults.sh"):  # local configuration wins
        path = ROOT / "kindle" / name
        m = re.search(r'^ARDUINO_HOST="([^"]+)"', path.read_text(), re.M) if path.exists() else None
        if m:
            return m.group(1)
    return ""


def make(out_dir, ssid, password, security, app_url):
    out_dir.mkdir(parents=True, exist_ok=True)
    wifi = segno.helpers.make_wifi(ssid=ssid, password=password or None,
                                   security=security if password else "nopass")
    save_qr(wifi, out_dir / "wifi.png", WIFI_PX)
    save_qr(segno.make(app_url, error="m"), out_dir / "app.png", APP_PX)
    (out_dir / "info.sh").write_text(
        "# Generated by tools/make_qr.py\n"
        f"QR_WIFI_SSID={shell_quote(ssid)}\n"
        f"QR_WIFI_PASS={shell_quote(password)}\n"
        f"QR_APP_URL={shell_quote(app_url)}\n"
    )


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--ssid", help="network name (asked for if missing)")
    p.add_argument("--security", default="WPA", choices=["WPA", "WEP"],
                   help="WPA also covers WPA2/WPA3 (default: WPA)")
    p.add_argument("--app-url", help="webapp address (default: http://ARDUINO_HOST/ from kindle/config.sh or defaults.sh)")
    p.add_argument("--out", default=ROOT / "kindle/qr", type=Path)
    args = p.parse_args()

    ssid = args.ssid or input("Guest WiFi network: ").strip()
    password = getpass.getpass("Password (empty for an open network): ")
    app_url = args.app_url or f"http://{arduino_host_from_config()}/"
    make(args.out, ssid, password, args.security, app_url)
    print(f"QR codes created in {args.out}. Copy the folder to /mnt/us/dashboard/qr/ on the Kindle.")


if __name__ == "__main__":
    main()
