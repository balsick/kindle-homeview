# set DIR (the panel folder) already.

. "$DIR/defaults.sh"
[ -f "$DIR/config.sh" ] && . "$DIR/config.sh"
QR_DIR=${QR_DIR:-$DIR/qr}   # generated by tools/make_qr.py
[ -f "$QR_DIR/info.sh" ] && . "$QR_DIR/info.sh"

RUN=${RUN:-/tmp/dashboard}

# The Kindle 5's BusyBox (1.7.2) is old: no "command -v", no od, grep
# without -E. have() uses which, which is there.
have() { which "$1" >/dev/null 2>&1; }
VERSION=$(cat "$DIR/VERSION" 2>/dev/null)

# http_get URL TIMEOUT_S FILE: wget with a hand-made timeout, because the
# Kindle's BusyBox wget may not support -T.
# The timer also kills its sleep when the download finishes first, so no
# processes are left behind (nor open pipes, for whoever reads the output).
http_get() {
  rm -f "$3"
  wget -q -O "$3" "$1" 2>/dev/null &
  local pid=$!
  (
    sleep "$2" &
    s=$!
    trap 'kill $s 2>/dev/null; exit 0' TERM
    wait $s && kill "$pid" 2>/dev/null
  ) >/dev/null 2>&1 &
  local timer=$!
  wait "$pid" 2>/dev/null
  local rc=$?
  kill "$timer" 2>/dev/null
  return $rc
}

